#!/usr/bin/env bash
# Private, disposable MySQL server for the integration tests.
#
# Runs from .dev/mysql (git-ignored) on port 3307 with its own socket, so it
# never touches the developer's main MySQL server. Only listens on 127.0.0.1.
#
#   bin/test-db.sh start   # initialise on first run, start, create dms_test + tests/.env
#   bin/test-db.sh stop
#   bin/test-db.sh status
#   bin/test-db.sh reset   # stop and delete all data (re-created on next start)
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
DEV="$ROOT/.dev/mysql"
DATA="$DEV/data"
SOCK="$DEV/mysql.sock"
PID="$DEV/mysqld.pid"
LOG="$DEV/mysqld.log"
PORT="${DMS_TEST_DB_PORT:-3307}"
ENV_FILE="$ROOT/tests/.env"

running() { [[ -f "$PID" ]] && kill -0 "$(cat "$PID")" 2>/dev/null; }
client() { mysql --no-defaults -uroot --socket="$SOCK" "$@"; }

start() {
  mkdir -p "$DEV"
  if [[ ! -d "$DATA" ]]; then
    echo "Initialising private MySQL data directory…"
    mysqld --no-defaults --initialize-insecure --datadir="$DATA" --log-error="$LOG"
  fi
  if ! running; then
    mysqld --no-defaults --datadir="$DATA" --socket="$SOCK" --port="$PORT" \
      --bind-address=127.0.0.1 --mysqlx=OFF --pid-file="$PID" --log-error="$LOG" &
    for _ in $(seq 1 60); do
      client -e "SELECT 1" >/dev/null 2>&1 && break
      sleep 0.5
    done
    client -e "SELECT 1" >/dev/null 2>&1 || { echo "MySQL did not start; see $LOG" >&2; exit 1; }
  fi

  if [[ ! -f "$ENV_FILE" ]]; then
    local pw
    pw="$(openssl rand -hex 16)"
    client <<SQL
CREATE DATABASE IF NOT EXISTS dms_test CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
CREATE USER IF NOT EXISTS 'dms_test'@'localhost' IDENTIFIED BY '$pw';
ALTER USER 'dms_test'@'localhost' IDENTIFIED BY '$pw';
GRANT ALL ON dms_test.* TO 'dms_test'@'localhost';
SQL
    umask 077
    cat > "$ENV_FILE" <<ENV
# Generated by bin/test-db.sh — private test server in .dev/mysql. Git-ignored.
DMS_TEST_DB_NAME=dms_test
DMS_TEST_DB_USER=dms_test
DMS_TEST_DB_PASSWORD=$pw
DMS_TEST_DB_HOST=localhost:$SOCK
ENV
    echo "Wrote tests/.env"
  fi
  echo "Test MySQL running (socket $SOCK, port $PORT)."
}

stop() {
  if running; then
    client -e "SHUTDOWN" || kill "$(cat "$PID")"
    for _ in $(seq 1 40); do running || break; sleep 0.25; done
    echo "Stopped."
  else
    echo "Not running."
  fi
}

case "${1:-}" in
  start)  start ;;
  stop)   stop ;;
  status) running && echo "Running (pid $(cat "$PID"))" || echo "Not running" ;;
  reset)  stop; rm -rf "$DEV"; rm -f "$ENV_FILE"; echo "Deleted $DEV and tests/.env" ;;
  *) echo "Usage: $0 {start|stop|status|reset}" >&2; exit 2 ;;
esac
